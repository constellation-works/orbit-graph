#!/usr/bin/env bash
# Scripted baseline for one study: everything an agent can learn about the
# change from Git plus the `orbit-graph` CLI alone, with wall-clock recorded.
#
# Usage: baseline.sh <study-id>
#
# Writes $OUT/study-<id>/baseline.txt (full transcript),
# baseline-symbols.txt (the names the diff yielded) and baseline-timing.tsv.
#
# This is the comparison arm for service-study.sh. The comparison is
# AGENT-ONLY: it measures the commands an agent issues, not what a person
# experiences in a browser.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_binaries

want="${1:?usage: baseline.sh <study-id>}"
repo=""; base=""; head=""
for line in "${STUDIES[@]}"; do
  [ "$(study_field "$line" 1)" = "$want" ] || continue
  repo=$(study_field "$line" 2); base=$(study_field "$line" 3); head=$(study_field "$line" 4)
done
: "${repo:?unknown study $want}"

dir="$REPOS/$repo"
outdir="$OUT/study-$want"; mkdir -p "$outdir"
report="$outdir/baseline.txt"
symbols="$outdir/baseline-symbols.txt"
tree="$SCRATCH/baseline-tree-$want"

# Candidate kinds, in the order the CLI is probed. The baseline has no
# symbol table of its own, so it must guess the kind a selector needs.
KINDS="function method struct enum trait type_alias class"

start=$(date +%s.%N)

{
  echo "# baseline for study $want: $repo ${base:0:12}..${head:0:12}"
  echo "# generated by docs/evaluation/change-explorer/scripts/baseline.sh"
  echo
  echo "## git diff --stat"
  git -C "$dir" diff --stat "$base" "$head"
} > "$report"

# Names the diff itself offers: added or removed declaration headers.
git -C "$dir" diff -U0 "$base" "$head" -- '*.rs' '*.py' \
  | grep -E '^[-+][[:space:]]*(pub(\([^)]*\))?[[:space:]]+)?(async[[:space:]]+)?(unsafe[[:space:]]+)?(fn|struct|enum|trait|type|def|class)[[:space:]]' \
  | sed -E 's/^[-+][[:space:]]*//; s/^(pub(\([^)]*\))?[[:space:]]+)?(async[[:space:]]+)?(unsafe[[:space:]]+)?(fn|struct|enum|trait|type|def|class)[[:space:]]+//; s/[^A-Za-z0-9_].*$//' \
  | grep -E '^[A-Za-z_][A-Za-z0-9_]*$' | sort -u > "$symbols" || true

{
  echo
  echo "## changed declaration names recovered from the diff ($(wc -l < "$symbols"))"
  cat "$symbols"
  echo
  echo "## git grep -w per name at head, total match count"
} >> "$report"
while IFS= read -r sym; do
  n=$( { git -C "$dir" grep -c -w -- "$sym" "$head" 2>/dev/null || true; } | awk -F: '{s+=$NF} END {print s+0}')
  printf '%s\t%s\n' "$sym" "$n" >> "$report"
done < "$symbols"

# `orbit-graph` indexes the checkout it is run from, so head is materialized as
# a detached worktree of the scratch clone. Nothing outside $SCRATCH is written.
git worktree remove --force "$tree" 2>/dev/null || true
rm -rf "$tree"
git -C "$dir" worktree add --detach --quiet "$tree" "$head"

{
  echo
  echo "## orbit-graph sync --full (head)"
} >> "$report"
( cd "$tree" && "$GRAPH" --format json sync --full ) >> "$report" 2>&1 || true

{
  echo
  echo "## orbit-graph refs/impact per name (kind probed: $KINDS)"
} >> "$report"
while IFS= read -r sym; do
  echo "### $sym" >> "$report"
  hits=$(cd "$tree" && "$GRAPH" --format json search "$sym" --kind symbol --limit 20 \
         | jq -r --arg n "$sym" '[.matches[]? | select(.name == $n) | .path] | unique | .[]')
  if [ -z "$hits" ]; then
    echo "no indexed symbol named $sym" >> "$report"
    continue
  fi
  while IFS= read -r path; do
    for kind in $KINDS; do
      sel="symbol:$path#$sym:$kind"
      found=$(cd "$tree" && "$GRAPH" --format json show "$sel" | jq -r 'if . == null then "no" else "yes" end')
      [ "$found" = "yes" ] || continue
      echo "selector $sel" >> "$report"
      ( cd "$tree" && "$GRAPH" --format json refs "$sel" ) >> "$report" 2>&1 || true
      ( cd "$tree" && "$GRAPH" --format json impact "$sel" ) >> "$report" 2>&1 || true
      break
    done
  done <<< "$hits"
done < "$symbols"

git -C "$dir" worktree remove --force "$tree"
end=$(date +%s.%N)

printf 'study\t%s\nrepo\t%s\nbase\t%s\nhead\t%s\nnames_probed\t%s\nbaseline_wall_seconds\t%.2f\n' \
  "$want" "$repo" "$base" "$head" "$(wc -l < "$symbols")" "$(echo "$end - $start" | bc)" \
  | tee "$outdir/baseline-timing.tsv"
